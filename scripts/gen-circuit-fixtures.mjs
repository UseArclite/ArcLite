// Generate the Schnorr signatures the batch_cross tests need.
//
// Noir cannot sign: `s = k − e·sk` is arithmetic modulo Grumpkin's scalar field, which is BN254's
// *base* field and not the `Field` a circuit works in. Doing it there would mean a bignum
// library for the sake of test fixtures.
//
// Generating them here is better anyway — a fixture the circuit accepts is direct evidence that
// the TypeScript signer and the in-circuit verifier agree, which is the thing that actually has
// to hold.
//
//   bun scripts/gen-circuit-fixtures.mjs
import { publicKey, sign, verify } from "../src/lib/notes/grumpkin.ts";
import { hash2 } from "../src/lib/notes/poseidon2.ts";
import { commitment, nullifier, ownerOf } from "../src/lib/notes/note.ts";

const DOMAIN_SPEND = 0x7370656e64n; // "spend" — five bytes, not four
const WINDOW = 77n;
const SUB_BATCH = 0n;
const ASSET = 1n;
/// A buyer funds the trade with a quote note, a seller with the asset itself. The *message*
/// still names the traded asset — that is what the order is about — so only the commitment moves.
const QUOTE_ASSET_ID = 4n;
const noteAsset = (side) => (side === 0n ? QUOTE_ASSET_ID : ASSET);

/**
 * The message `batch_cross` verifies. Must match main.nr exactly.
 *
 * Not bound to the slot or the sub-batch: both are assigned by the sealer after submission, so a
 * trader signing offline cannot know them. The nullifier inside the message is what stops the
 * signature moving anywhere — a nullifier may be published once.
 */
const spendMessage = (assetId, side, quantity, nul) =>
  hash2(hash2(DOMAIN_SPEND, WINDOW), hash2(hash2(assetId, side), hash2(quantity, nul)));

/** Leaf index → the zero-padded tree the tests build. */
function treeFor(commitments) {
  const zeros = [];
  let z = 0n;
  for (let i = 0; i < 24; i++) { zeros.push(z); z = hash2(z, z); }
  const path = (index) => {
    const out = [];
    let level = [...commitments];
    let idx = index;
    for (let d = 0; d < 24; d++) {
      const sib = idx ^ 1;
      out.push(sib < level.length ? level[sib] : zeros[d]);
      const next = [];
      for (let i = 0; i < level.length; i += 2) {
        next.push(hash2(level[i], i + 1 < level.length ? level[i + 1] : zeros[d]));
      }
      level = next; idx >>= 1;
    }
    return out;
  };
  return { path };
}

function scenario(name, orders) {
  const notes = orders.map((o) => {
    const pk = publicKey(o.secret);
    return { ...o, pk, owner: ownerOf(pk.x, pk.y, o.npk) };
  });
  const commitments = notes.map((n) =>
    commitment({ assetId: noteAsset(n.side), units: n.units, owner: n.owner, nsecret: n.nsecret }));

  const lines = [`// ${name} — generated by scripts/gen-circuit-fixtures.mjs, do not hand-edit.`];
  notes.forEach((n, i) => {
    const nul = nullifier(commitments[i], n.nsecret, BigInt(i));
    const msg = spendMessage(ASSET, n.side, n.quantity, nul);
    const sig = sign(n.secret, msg);
    if (!verify(n.pk, sig, msg)) throw new Error(`signature ${i} does not verify locally`);
    lines.push(
      `    c.sig_s_lo[${i}] = 0x${sig.sLo.toString(16)};`,
      `    c.sig_s_hi[${i}] = 0x${sig.sHi.toString(16)};`,
      `    c.sig_e_lo[${i}] = 0x${sig.eLo.toString(16)};`,
      `    c.sig_e_hi[${i}] = 0x${sig.eHi.toString(16)};`,
    );
  });
  console.log(lines.join("\n"));
  console.log();
  notes.forEach((n, i) => {
    console.log(`// slot ${i}: pk.x = 0x${n.pk.x.toString(16)}`);
    console.log(`// slot ${i}: pk.y = 0x${n.pk.y.toString(16)}`);
  });
  console.log();
}

// The honest case: a 100-unit buy and a 40-unit sell.
scenario("honest_case", [
  { secret: 111n, npk: 7n, nsecret: 333n, units: 100n, quantity: 100n, side: 0n },
  { secret: 222n, npk: 9n, nsecret: 444n, units: 40n, quantity: 40n, side: 1n },
]);

// an_order_smaller_than_its_note_returns_the_whole_remainder: the seller's note holds 100 but
// only 40 is offered, so the signed quantity differs from the note's units.
scenario("partial_offer_case", [
  { secret: 111n, npk: 7n, nsecret: 333n, units: 100n, quantity: 100n, side: 0n },
  { secret: 222n, npk: 9n, nsecret: 444n, units: 100n, quantity: 40n, side: 1n },
]);

// pro_rata_splits_a_shared_side: two buyers against one seller, so the shared side is split.
// Different quantities mean different signed messages, so it needs its own signatures.
scenario("pro_rata_case", [
  { secret: 111n, npk: 7n, nsecret: 333n, units: 30n, quantity: 30n, side: 0n },
  { secret: 222n, npk: 9n, nsecret: 444n, units: 20n, quantity: 20n, side: 1n },
  { secret: 777n, npk: 11n, nsecret: 888n, units: 10n, quantity: 10n, side: 0n },
]);

// a_buyer_pays_quote_for_what_it_receives: the only scenario at realistic decimals. Everywhere
// else units are single digits, so `filled × ref / 10^30` floors to zero and the quote leg is
// invisible — which is exactly how a buy side that moved no quote at all went unnoticed.
// One whole 18-decimal unit at $222.45 costs 222450000 six-decimal USDG.
scenario("realistic_scale_case", [
  { secret: 111n, npk: 7n, nsecret: 333n, units: 300000000n, quantity: 10n ** 18n, side: 0n },
  { secret: 222n, npk: 9n, nsecret: 444n, units: 10n ** 18n, quantity: 10n ** 18n, side: 1n },
]);
